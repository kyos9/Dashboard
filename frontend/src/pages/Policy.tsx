import { useAuth } from '../components/AuthGate'
import { POLICY_EFFECTIVE } from '../lib/policy'

/**
 * 개인정보처리방침 · 이용약관 (ROADMAP 4-4b, 4단계 8번).
 *
 * 남의 계정 정보를 받는 순간 필요하고, 구글 로그인 동의 화면도 이 주소를 요구한다. 그래서
 * **로그인 전에도 열린다.**
 *
 * 적는 원칙: 코드가 실제로 하는 것만 적는다. 보관 기간·한도 같은 숫자는 서버 설정과 같아야
 * 한다 — 한도는 `backend/tests/test_policy_page.py` 가 서버 값과 대조한다.
 */
export function Policy() {
  const { contact } = useAuth()
  const ask = contact ? (
    <>
      관리자에게 문의하세요: <b className="contact-line">{contact}</b>
    </>
  ) : (
    '관리자에게 문의하세요.'
  )

  return (
    <article className="policy">
      <h2>개인정보처리방침 · 이용약관</h2>
      <p className="hint">시행일 {POLICY_EFFECTIVE}</p>

      <p>
        신호판은 개인이 취미로 운영하는 무료 도구입니다. 회사가 운영하는 서비스가 아니고, 이 서버의
        관리자가 직접 돌봅니다. {ask}
      </p>

      <h3>1. 받는 정보</h3>
      <ul>
        <li>
          <b>구글 로그인</b> — 구글 계정 식별자, 이메일 주소, 이름. 비밀번호는 받지 않습니다 (구글이
          확인합니다).
        </li>
        <li>
          <b>이용 기록</b> — 가입한 때, 마지막으로 로그인한 때, 가입 승인 상태.
        </li>
        <li>
          <b>내가 입력한 것</b> — 담은 종목과 표시 이름·구분, 보유수량·평단가·현금, 목표 비중·밴드·리뷰
          설정, 기준통화·직접 넣은 환율, 리밸런싱 기록, 홈에 올린 매크로 지표.
        </li>
      </ul>

      <h3>2. 쓰는 곳</h3>
      <ul>
        <li>로그인과 계정 구분 — 계정마다 자기 종목과 포트폴리오가 따로 보이게 합니다.</li>
        <li>
          가입 승인 — 관리자의 사용자 목록에 <b>이메일·이름·가입일·마지막 접속·담은 종목 수</b>가
          나옵니다.
        </li>
        <li>광고·분석·판매에는 쓰지 않습니다.</li>
      </ul>

      <h3>3. 다른 곳에 주는 것</h3>
      <p>
        없습니다. 시세와 지표를 받으려고 야후 파이낸스·네이버 금융·Stooq·미국 연준(FRED)·CNN 같은 공개
        출처에 <b>종목 코드와 지표 이름만</b> 보냅니다 — 누가 담았는지는 보내지 않습니다. 구글에는
        로그인할 때만 연결합니다.
      </p>

      <h3>4. 쿠키와 이 기기에 저장하는 것</h3>
      <ul>
        <li>
          <b>로그인 쿠키 1개</b> — 로그인을 유지하는 데 꼭 필요합니다. 최대 30일, 나가기를 누르면
          지웁니다. 로그인하는 동안에는 확인용 쿠키를 10분 동안 잠깐 씁니다.
        </li>
        <li>화면 테마(밝게·어둡게)와 설치 안내 숨김은 서버가 아니라 이 기기의 브라우저에만 저장합니다.</li>
        <li>광고·추적 쿠키는 없습니다.</li>
      </ul>

      <h3>5. 보관과 삭제</h3>
      <ul>
        <li>
          <b>탈퇴</b>하면 계정과 내가 입력한 기록을 바로 지웁니다. 다만 서버 백업(하루 한 번, 최근
          7벌)에 <b>최대 7일</b> 남았다가 차례로 지워집니다.
        </li>
        <li>
          서버 로그에는 종목 코드와 오류가 남습니다. 관리자만 볼 수 있고, 정해진 크기가 차면 오래된
          것부터 지워집니다.
        </li>
        <li>
          시세·지표는 누구의 것도 아닌 공용 기록이라 탈퇴하거나 종목을 삭제해도 남습니다. 거기엔 나를
          가리키는 정보가 없습니다.
        </li>
        <li>
          거절·차단된 계정의 이메일과 이름은 같은 계정이 신청을 되풀이하지 못하도록 남겨둡니다. 승인을
          기다리거나 거절·차단된 계정에는 탈퇴 버튼이 없으니, 지우고 싶으면 {ask}
        </li>
      </ul>

      <h3>6. 운영자가 볼 수 있는 것</h3>
      <p>
        관리자 화면에는 2번의 사용자 목록만 나옵니다. 다만 서버를 운영하는 사람은 기술적으로 데이터베이스
        전체에 접근할 수 있습니다 — 숨기지 않고 적어둡니다.
      </p>

      <h3>7. 내 권리</h3>
      <p>
        내 정보는 화면에서 보고 고칠 수 있고, 헤더의 <b>탈퇴</b>로 지울 수 있습니다. 그 밖의 요청은 {ask}
      </p>

      <h2>이용약관</h2>
      <ul>
        <li>
          <b>참고용입니다.</b> 시그널·지표·리밸런싱 안내는 정해진 공식으로 계산한 참고 정보이며 투자
          권유나 자문이 아닙니다. 투자 판단과 그 결과의 책임은 본인에게 있습니다.
        </li>
        <li>
          <b>시세는 무료 공개 출처에서 옵니다.</b> 늦거나, 틀리거나, 빠질 수 있습니다.
        </li>
        <li>
          <b>보증하지 않습니다.</b> 개인이 운영하는 무료 서버라 예고 없이 멈추거나, 기능이 바뀌거나,
          데이터가 사라질 수 있습니다. 중요한 기록은 따로 남겨두세요.
        </li>
        <li>
          <b>이용 한도</b> — 무료 서버를 모두가 나눠 쓰기 위해: 종목은 한 사람이 30개까지, 처음 받는 종목은
          하루 10개까지, 같은 종목 새로고침은 10분에 한 번, 바깥 검색은 분당 20번까지입니다.
        </li>
        <li>
          <b>이용 제한</b> — 관리자는 가입 신청을 거절하거나 이용을 멈출(차단) 수 있습니다. 서버에 무리를
          주거나 다른 사람을 방해하는 사용이 그 이유가 됩니다.
        </li>
        <li>
          <b>바뀔 때</b> — 방침이나 약관이 바뀌면 이 페이지의 시행일을 새로 적습니다.
        </li>
      </ul>
    </article>
  )
}
